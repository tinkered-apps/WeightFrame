"""Convert official CDC / WHO BMI-for-age LMS reference tables into public/js/data/growth-refs.js.

Sources (downloaded unchanged into data-src/):
  cdc_bmiagerev.csv   CDC 2000 BMI-for-age, 2-20 y (LMS by half month)
                      https://www.cdc.gov/growthcharts/data/zscore/bmiagerev.csv
  who2007_*.xlsx      WHO 2007 Growth Reference, BMI-for-age 5-19 y (LMS by month)
                      https://www.who.int/tools/growth-reference-data-for-5to19-years/indicators/bmi-for-age
  who2006_*.xlsx      WHO 2006 Child Growth Standards, BMI-for-age 0-5 y (LMS by day)
                      https://www.who.int/toolkits/child-growth-standards/standards/body-mass-index-for-age-bmi-for-age

Run:  python scripts/build_growth_data.py
Only the Python standard library is used. L, M and S are copied without rounding beyond
what is needed to reproduce the published tables (7 significant digits).
"""
import csv
import json
import os
import xml.etree.ElementTree as ET
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "data-src")
OUT = os.path.join(ROOT, "public", "js", "data", "growth-refs.js")
NS = "{http://schemas.openxmlformats.org/spreadsheetml/2006/main}"

# WHO 2006 is only needed from 2 years (730.5 days); keep a small margin before that.
WHO2006_FIRST_DAY = 700


def sig(x, digits=7):
    return float(f"{float(x):.{digits}g}")


def read_xlsx(path):
    z = zipfile.ZipFile(path)
    shared = []
    if "xl/sharedStrings.xml" in z.namelist():
        root = ET.fromstring(z.read("xl/sharedStrings.xml"))
        for si in root.findall(f"{NS}si"):
            shared.append("".join(t.text or "" for t in si.iter(f"{NS}t")))
    root = ET.fromstring(z.read("xl/worksheets/sheet1.xml"))
    rows = []
    for r in root.iter(f"{NS}row"):
        vals = []
        for c in r.findall(f"{NS}c"):
            v = c.find(f"{NS}v")
            val = v.text if v is not None else ""
            if c.get("t") == "s" and val != "":
                val = shared[int(val)]
            vals.append(val)
        rows.append(vals)
    header, body = rows[0], rows[1:]
    idx = {name: header.index(name) for name in header}
    return idx, body


def who_table(path, age_col, first_age=None):
    idx, body = read_xlsx(path)
    out = []
    for r in body:
        age = int(float(r[idx[age_col]]))
        if first_age is not None and age < first_age:
            continue
        out.append([age, sig(r[idx["L"]]), sig(r[idx["M"]]), sig(r[idx["S"]])])
    return out


def cdc_table(path):
    male, female = [], []
    with open(path, newline="") as f:
        for row in csv.DictReader(f):
            if row["Sex"] == "Sex":  # repeated header between the two sexes
                continue
            rec = [float(row["Agemos"]), sig(row["L"], 10), sig(row["M"], 10), sig(row["S"], 10)]
            (male if row["Sex"] == "1" else female).append(rec)
    return male, female


def main():
    cdc_m, cdc_f = cdc_table(os.path.join(SRC, "cdc_bmiagerev.csv"))
    data = {
        "cdc2000": {
            "unit": "months",
            "source": "CDC 2000 BMI-for-age growth charts (bmiagerev.csv)",
            "male": cdc_m,
            "female": cdc_f,
        },
        "who2007": {
            "unit": "months",
            "source": "WHO 2007 Growth Reference 5-19 y, BMI-for-age expanded tables",
            "male": who_table(os.path.join(SRC, "who2007_boys.xlsx"), "Month"),
            "female": who_table(os.path.join(SRC, "who2007_girls.xlsx"), "Month"),
        },
        "who2006": {
            "unit": "days",
            "source": "WHO 2006 Child Growth Standards, BMI-for-age expanded tables (from day %d)"
            % WHO2006_FIRST_DAY,
            "male": who_table(os.path.join(SRC, "who2006_boys.xlsx"), "Day", WHO2006_FIRST_DAY),
            "female": who_table(os.path.join(SRC, "who2006_girls.xlsx"), "Day", WHO2006_FIRST_DAY),
        },
    }
    body = json.dumps(data, separators=(",", ":"))
    js = (
        "/* AUTO-GENERATED by scripts/build_growth_data.py - do not edit by hand.\n"
        " * Rows are [age, L, M, S]. See the script header for sources. */\n"
        "(function (root, data) {\n"
        "  if (typeof module === 'object' && module.exports) module.exports = data;\n"
        "  else { root.FH = root.FH || {}; root.FH.growthData = data; }\n"
        "})(typeof self !== 'undefined' ? self : this, " + body + ");\n"
    )
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(js)
    for key, ref in data.items():
        print(key, "male", len(ref["male"]), "female", len(ref["female"]))
    print("wrote", OUT, len(js), "bytes")


if __name__ == "__main__":
    main()
